const htmlEl = document.documentElement;
const langButtons = [...document.querySelectorAll('.lang-btn')];
const navToggle = document.querySelector('.nav-toggle');
const mainNav = document.querySelector('.main-nav');
const STORAGE_KEY = 'egsg-language';
const DEFAULT_LANG = 'en';

function normalizeLanguage(lang) {
  return lang === 'ar' ? 'ar' : DEFAULT_LANG;
}

function getPreferredLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  const storedLang = localStorage.getItem(STORAGE_KEY);
  return normalizeLanguage(urlLang || storedLang || DEFAULT_LANG);
}

function applyLanguageToLinks(lang) {
  document.querySelectorAll('a[href]').forEach((link) => {
    const href = link.getAttribute('href');
    if (!href || href.startsWith('http') || href.startsWith('#') || href.startsWith('mailto:')) {
      return;
    }

    const hashIndex = href.indexOf('#');
    const hash = hashIndex >= 0 ? href.slice(hashIndex) : '';
    const pathAndQuery = hashIndex >= 0 ? href.slice(0, hashIndex) : href;
    const queryIndex = pathAndQuery.indexOf('?');
    const basePath = queryIndex >= 0 ? pathAndQuery.slice(0, queryIndex) : pathAndQuery;
    const existingQuery = queryIndex >= 0 ? pathAndQuery.slice(queryIndex + 1) : '';

    const allowedPages = ['index.html', 'fixtures.html', 'squad.html'];
    if (!allowedPages.includes(basePath.split('/').pop())) {
      return;
    }

    const params = new URLSearchParams(existingQuery);
    if (lang === DEFAULT_LANG) {
      params.delete('lang');
    } else {
      params.set('lang', lang);
    }

    const queryString = params.toString();
    const nextHref = `${basePath}${queryString ? `?${queryString}` : ''}${hash}`;
    link.setAttribute('href', nextHref);
  });
}

function syncUrlLanguage(lang) {
  const url = new URL(window.location.href);

  if (lang === DEFAULT_LANG) {
    url.searchParams.delete('lang');
  } else {
    url.searchParams.set('lang', lang);
  }

  const nextUrl = `${url.pathname}${url.search}${url.hash}`;
  window.history.replaceState({}, '', nextUrl);
}

function updateLanguage(lang) {
  const activeLang = normalizeLanguage(lang);
  const dictionary = translations[activeLang] || translations.en;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  htmlEl.lang = activeLang;
  htmlEl.setAttribute('dir', activeLang === 'ar' ? 'rtl' : 'ltr');
  document.body.style.direction = activeLang === 'ar' ? 'rtl' : 'ltr';
  localStorage.setItem(STORAGE_KEY, activeLang);
  syncUrlLanguage(activeLang);
  applyLanguageToLinks(activeLang);

  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === activeLang;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => updateLanguage(button.dataset.lang));
});

if (navToggle && mainNav) {
  navToggle.addEventListener('click', () => {
    const isOpen = mainNav.classList.toggle('open');
    navToggle.setAttribute('aria-expanded', String(isOpen));
  });

  mainNav.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      mainNav.classList.remove('open');
      navToggle.setAttribute('aria-expanded', 'false');
    });
  });
}

updateLanguage(getPreferredLanguage());
